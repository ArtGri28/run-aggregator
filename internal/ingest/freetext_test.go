package ingest

import "testing"

func TestRuDate(t *testing.T) {
	for in, want := range map[string]string{
		"10 октября": "10.10", "03 октября 2026": "03.10.2026", " 7  Мая ": "7.05",
		"10 - 11 октября": "10 - 11 октября", "10 мартобря": "10 мартобря", "": "",
	} {
		if got := RuDate(in); got != want {
			t.Errorf("RuDate(%q) = %q, want %q", in, got, want)
		}
	}
}

