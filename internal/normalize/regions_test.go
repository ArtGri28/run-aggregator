func TestRegionsTable(t *testing.T) {
	if len(rfSubjects) != 89 {
		t.Fatalf("rfSubjects: %d записей, want 89", len(rfSubjects))
	}
	owner := map[string]string{}
	for _, names := range rfSubjects {
		for _, n := range names {
			k := regionKey(n)
			if k == "" {
				t.Errorf("%q: пустой ключ", n)
			}
			if prev, ok := owner[k]; ok && prev != names[0] {
				t.Errorf("ключ %q: %q и %q", k, prev, names[0])
			}
			owner[k] = names[0]
		}
	}
	for _, n := range foreignNames {
		if c, ok := owner[regionKey(n)]; ok {
			t.Errorf("иностранное %q совпадает с субъектом РФ %q", n, c)
		}
	}
}

