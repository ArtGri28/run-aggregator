func TestClassifyRegionMarathonec(t *testing.T) {
	if len(marathonecOblast) != 83 {
		t.Fatalf("%d названий, want 83", len(marathonecOblast))
	}
	canon := map[string]string{}
	for _, n := range marathonecOblast {
		c, k := ClassifyRegion(n)
		if k != RegionRF {
			t.Errorf("ClassifyRegion(%q) = (%q, %v), want RegionRF", n, c, k)
			continue
		}
		if prev, ok := canon[c]; ok && !(prev == "Марий-Эл" && n == "Республика Марий Эл") {
			t.Errorf("%q и %q дают один субъект %q", prev, n, c)
		}
		canon[c] = n
	}
}

func TestClassifyPlace(t *testing.T) {
	tests := []struct {
		region, city, canonical string
		kind                    RegionKind
	}{
		{"Москва и Московская область", "Москва", "Москва", RegionRF},
		{"Москва и Московская область", "Красногорск", "Московская область", RegionRF},
		{"СПБ и Ленинградская область", "Санкт-Петербург", "Санкт-Петербург", RegionRF},
		{"СПБ и Ленинградская область", "Гатчина", "Ленинградская область", RegionRF},
		{"Московская область", "г. Москва", "Москва", RegionRF},
		{"Республика Крым", "Севастополь", "Севастополь", RegionRF},
		// город уточняет только окружающий его субъект
		{"Тверская область", "Москва", "Тверская область", RegionRF},
		{"Беларусь", "Минск", "", RegionForeign},
		{"Минская область", "Москва", "", RegionUnknown},
		{"", "Москва", "", RegionUnknown},
	}
	for _, tt := range tests {
		c, k := ClassifyPlace(tt.region, tt.city)
		if c != tt.canonical || k != tt.kind {
			t.Errorf("ClassifyPlace(%q, %q) = (%q, %v), want (%q, %v)", tt.region, tt.city, c, k, tt.canonical, tt.kind)
		}
	}
}
