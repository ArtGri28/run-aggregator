// regionGeneric — служебные слова, которые не различают субъекты.
var regionGeneric = map[string]bool{
	"республика": true, "респ": true, "область": true, "обл": true, "край": true,
	"автономный": true, "автономная": true, "округ": true, "ао": true, "аобл": true,
	"город": true, "г": true,
}

// regionKey: нижний регистр, ё→е, пунктуация → пробел, без служебных слов.
func regionKey(s string) string {
	var out []string
	for _, w := range strings.FieldsFunc(yoToE(strings.ToLower(s)), notLetterOrDigit) {
		if !regionGeneric[w] {
			out = append(out, w)
		}
	}
	return strings.Join(out, " ")
}

var (
	rfIndex      = map[string]string{} // regionKey → каноническое имя
	foreignIndex = map[string]bool{}
)

func init() {
	for _, names := range rfSubjects {
		for _, n := range names {
			rfIndex[regionKey(n)] = names[0]
		}
	}
	for _, n := range foreignNames {
		foreignIndex[regionKey(n)] = true
	}
}

// ClassifyRegion относит область к субъекту РФ (каноническое имя),
// к известной иностранной стране или к нераспознанным. Пустая строка —
// ("", RegionUnknown); пустую область вызывающий код считает отдельно,
// как пустое поле.
func ClassifyRegion(s string) (canonical string, kind RegionKind) {
	k := regionKey(s)
	switch {
	case k == "":
		return "", RegionUnknown
	case rfIndex[k] != "":
		return rfIndex[k], RegionRF
	case foreignIndex[k]:
		return "", RegionForeign
	}
	return "", RegionUnknown
}

// federalCityIn — город федерального значения → субъект вокруг него.
var federalCityIn = map[string]string{
	"Москва":          "Московская область",
	"Санкт-Петербург": "Ленинградская область",
	"Севастополь":     "Республика Крым",
}

// ClassifyPlace — ClassifyRegion с уточнением по городу: если источник
// дал субъект вокруг города федерального значения, а город — сам этот
// город («Москва и Московская область» + «Москва»), результат — город
// федерального значения (D-14).
func ClassifyPlace(region, city string) (canonical string, kind RegionKind) {
	canonical, kind = ClassifyRegion(region)
	if kind == RegionRF {
		if c, k := ClassifyRegion(City(city)); k == RegionRF && federalCityIn[c] == canonical {
			return c, kind
		}
	}
	return canonical, kind
}
